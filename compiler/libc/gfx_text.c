int gfx_char(int x, int y, int c, int fg, int bg)
{
    int col, row;
    unsigned int bits = 0, last = 0;
    if (c >= 32 && c < 127) {
        bits = font[2 * (c - 32)];
        last = font[2 * (c - 32) + 1];
    }
    if (bg != GFX_NONE)
        gfx_fill_rect(x, y, GFX_CHAR_WIDTH, GFX_CHAR_HEIGHT, bg);
    for (col = 0; col < 5; col++) {
        unsigned int column = col < 4 ? (bits >> (8 * col)) & 0xFF : last;
        for (row = 0; column != 0; row++, column >>= 1)
            if (column & 1)
                gfx_pixel(x + col, y + row, fg);
    }
    return x + GFX_CHAR_WIDTH;
}

int gfx_text(int x, int y, const char *s, int fg, int bg)
{
    int left = x;
    for (; *s; s++) {
        if (*s == '\n') {
            x = left;
            y += GFX_CHAR_HEIGHT;
        } else
            x = gfx_char(x, y, *s, fg, bg);
    }
    return x;
}
