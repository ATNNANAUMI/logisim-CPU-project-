/* inttypes.h - printf/scanf formats for stdint.h types (all 32 bits) */
#ifndef _INTTYPES_H
#define _INTTYPES_H

#include <stdint.h>

#define PRId32 "d"
#define PRIi32 "i"
#define PRIu32 "u"
#define PRIx32 "x"
#define PRIX32 "X"
#define PRIo32 "o"
#define PRIdMAX "d"
#define PRIuMAX "u"
#define PRIxMAX "x"
#define PRIdPTR "d"
#define PRIuPTR "u"
#define PRIxPTR "x"
#define SCNd32 "d"
#define SCNi32 "i"
#define SCNu32 "u"
#define SCNx32 "x"

#endif
